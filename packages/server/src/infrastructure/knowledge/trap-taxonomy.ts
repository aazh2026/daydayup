/**
 * 错因类型学（Trap Taxonomy）—— 把错因资产归到**可统计的类型**上。
 *
 * 背景：
 * 错因资产（TrapSet）里的每条 `wrong` 都是一句自然语言，例如
 *   - 「把序数当基数用，问「第几个」时回答总数。」
 *   - 「认为 0 是最小的正数。」
 *   - 「把长音当作短音读，忽略音长。」
 * 五维错因（知识/方法/计算/熟练度/审题）来自 AI 诊断，是**另一条轴**；
 * 报告页要回答的是「学生的错误集中在哪些**具体陷阱形态**上」。
 * 这两者无法互相替代，所以这里单建一条轴。
 *
 * 为什么用「模式匹配」而不是让模型分类：
 *   - 错因文本来自源项目原句（红线：不许模型改写），用规则分类可以保证
 *     **同一句话每次都归到同一类**（可复现、可审计）；
 *   - 分类结果只用于统计展示，不影响判题与掌握度迁移，风险面小；
 *   - 未命中任何模式的条目归入「其他易错点」，不丢数据。
 *
 * 分类维度（`TrapType`）：与错因文本的实际措辞一一对应，见 `TRAP_TYPE_LABELS`。
 */

/** 错因形态类型。 */
export type TrapType =
  | '概念混淆' // 把两个概念搞混（基数/序数、正数/非正数、长音/短音）
  | '规则误用' // 记错/用错规则（符号、否定、公式）
  | '审题遗漏' // 漏看条件（题目条件没读全）
  | '计算失误' // 算错、化简错、单位换算错
  | '表达不规范' // 表述/格式/书写问题
  | '知识缺失' // 压根不会/没学过
  | '其他易错点'; // 未命中任何模式（兜底，不丢数据）

export const TRAP_TYPE_LABELS: Record<TrapType, string> = {
  概念混淆: '把两个概念搞混（分不清易混点）',
  规则误用: '规则记错或用错（公式/符号/否定）',
  审题遗漏: '漏看题目条件或问法',
  计算失误: '算错、化简错或单位换算错',
  表达不规范: '表述或书写不规范',
  知识缺失: '知识点尚未掌握',
  其他易错点: '其他易错点',
};

/**
 * 分类规则表。
 *
 * 顺序即优先级：先匹配到的规则胜出。
 * `pattern` 必须命中「错误表现」文本（`wrong`，必要时拼上 `why`/`right`）。
 */
interface TrapTypeRule {
  type: TrapType;
  pattern: RegExp;
}

/**
 * 规则表（顺序敏感）。
 *
 * 「概念混淆」排在最前：它通常带有明确的「把 A 当 B」「误以为」句式，
 * 特征最鲜明，误伤概率最低。
 */
const RULES: TrapTypeRule[] = [
  {
    // 「把 A 当成 B」「把 A 当 B」「误以为」「分不清」「搞混」「混淆」
    //
    // 注意：资产里的高频句式是「把序数当基数用」「把长音当作短音读」——
    // `当` 后面跟的常常是**宾语**（基数/短音），而不是「成/作」，
    // 所以这里同时匹配「把 A 当 B」与「把 A 当成/当作 B」。
    type: '概念混淆',
    pattern:
      /把[^，。；]{1,24}(?:当成|当作|误当作|误当成|当成|当|误当)|误以为|分不清|搞混|混淆|误认|张冠李戴|以偏概全|认为[^，。；]{1,24}(?:是|为)|概念(?:不清|模糊)/,
  },
  {
    // 「漏看」「忽略」「没注意」「遗漏」「审题」「条件」
    type: '审题遗漏',
    pattern:
      /漏(?:看|读|掉|了)|忽略(?:了)?|没(?:有)?注意|遗漏|审题|未(?:考虑|注意|看到)|条件(?:没|未)|忘记(?:了)?(?:条件|题目|看)/,
  },
  {
    // 「符号搞错」「记错」「用错」「公式」「负号」「定义」「法则」
    type: '规则误用',
    pattern:
      /记错|用错|弄错(?:了)?(?:公式|法则|定义|规则)|公式(?:记错|写错|用错)|负号|符号(?:错|搞错|弄错)|法则|定理|定义(?:记错|不清|模糊)|套错|用错(?:公式|定理|法则)|应为|应该是|实际(?:是|上)却/,
  },
  {
    // 「算错」「化简」「进位」「约分」「单位」「计算」「四舍五入」
    type: '计算失误',
    pattern:
      /算错|计算(?:错|失误|出错)|化简|约分|通分|进位|退位|四舍五入|单位(?:换算|转换)|乘以|除以(?:错|时)|小数点|符号(?:位|放错)|漏乘|多乘|根号|平方/,
  },
  {
    // 「写错」「不完整」「格式」「表述」「答非所问」「步骤」
    type: '表达不规范',
    pattern:
      /书写|格式|表述|表达(?:不|错)|答非所问|步骤(?:不|错)|没有(?:写|写清|写出|过程)|字迹|书写不规范|漏写/,
  },
  {
    // 「不会」「没学」「基础薄弱」「完全不懂」「根本」
    type: '知识缺失',
    pattern:
      /不会|不懂|没(?:学|掌握|接触|接触过)|尚未|基础(?:薄弱|不牢|不)|完全(?:不会|不懂|没)|根本(?:不会|不懂)|尚未学习|不熟悉/,
  },
];

/**
 * 给一条错因文本分类。
 *
 * @param text 错因文本（通常是 `wrong`，可拼接 `why`/`right`）
 * @returns 命中的类型；未命中任何规则返回「其他易错点」
 */
export function classifyTrapText(text: string | undefined | null): TrapType {
  if (!text) return '其他易错点';
  const s = String(text);
  for (const rule of RULES) {
    if (rule.pattern.test(s)) return rule.type;
  }
  return '其他易错点';
}

/** 分类规则表对外暴露（供测试与文档核对）。 */
export function listTrapTypeRules(): Array<{ type: TrapType; pattern: string }> {
  return RULES.map((r) => ({ type: r.type, pattern: r.pattern.source }));
}

/** 所有类型（含兜底），按展示顺序。 */
export function listTrapTypes(): TrapType[] {
  return [
    '概念混淆',
    '规则误用',
    '审题遗漏',
    '计算失误',
    '表达不规范',
    '知识缺失',
    '其他易错点',
  ];
}
